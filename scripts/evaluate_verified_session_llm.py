"""Bounded real API comparison on a new local-authority development cohort.

This is never a retroactive repair or independent acceptance of the historical36.
"""

import argparse
import asyncio
import hashlib
import json
import os
import time
from pathlib import Path

from dotenv import dotenv_values
from openai import AsyncOpenAI

from app.grounded_prompting import (
    GROUNDED_INSTRUCTIONS,
    VERIFIED_SESSION_INSTRUCTIONS,
    grounded_input,
    grounded_output_type,
    validate_grounded,
)
from app.services.session_analysis_evidence import collect_session_evidence
from scripts.compare_llm_grounded import compare_rows
from scripts.evaluate_llm_grounded import (
    INPUT_RATE,
    MODEL,
    OUTPUT_RATE,
    metrics,
    prediction,
    reservation,
)
from scripts.local_session_analysis_lab import (
    SCENARIOS,
    LocalSessionAnalysisLab,
    remote_policy_bundle,
)


async def run(directory, key_file=None, *, max_budget=2.5, repetitions=2):
    if not 0 < max_budget <= 2.5 or repetitions != 2:
        raise ValueError("evaluation_options")
    directory = Path(directory)
    if directory.exists():
        raise ValueError("output_exists")
    key = os.environ.get("OPENAI_API_KEY") or (
        dotenv_values(key_file).get("OPENAI_API_KEY") if key_file else None
    )
    if not key:
        raise ValueError("missing_credential")
    directory.mkdir(parents=True)
    private = directory / "private"
    private.mkdir()
    root = Path(__file__).resolve().parents[1]
    sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
    plan = {
        "schema": "verified-session-local-api-comparison-1",
        "model": MODEL,
        "reasoning_effort": "low",
        "max_output_tokens": 2400,
        "max_retries": 0,
        "concurrency_per_runner": 1,
        "max_requests": 48,
        "max_budget_usd": max_budget,
        "repetitions": repetitions,
        "cases_per_repetition": 12,
        "normal": 6,
        "threat": 6,
        "families": 12,
        "scenarios": SCENARIOS,
        "server_policy": remote_policy_bundle(),
        "label_source": "predeclared local scenario intent, never generated by engine or model",
        "historical_cases_modified": False,
        "independent_evaluation": False,
        "external_enterprise_SSO": False,
        "rates_source": "https://developers.openai.com/api/docs/models/gpt-5.4-mini",
        "input_per_million": 0.75,
        "output_per_million": 4.5,
        "source_pins": {
            f: sha(root / f)
            for f in (
                "scripts/evaluate_verified_session_llm.py",
                "scripts/local_session_analysis_lab.py",
                "app/services/session_analysis_evidence.py",
                "app/grounded_prompting.py",
                "app/analyzers/openai_analyzer.py",
                "app/analyzers/hybrid.py",
                "app/main.py",
                "app/services/zero_trust.py",
                "app/services/trusted_signals.py",
                "app/models.py",
                "app/config.py",
            )
        },
    }
    (directory / "plan.json").write_bytes((json.dumps(plan, indent=2) + "\n").encode())
    snapshots = directory / "source-snapshot"
    for f in plan["source_pins"]:
        target = snapshots / f
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes((root / f).read_bytes())
    lab = LocalSessionAnalysisLab(private / "authority")
    rows = []
    attempts = 0
    reserved = 0.0
    fatal = None
    async with AsyncOpenAI(
        api_key=key, base_url="https://api.openai.com/v1", timeout=45, max_retries=0
    ) as client:
        for repetition in range(repetitions):
            for index, spec in enumerate(SCENARIOS):
                # State/proofs use actual wall time, not a fabricated historical clock.
                signal, _ = lab.create(spec)
                (private / f"signed-{repetition}-{index}.json").write_bytes(
                    signal.model_dump_json().encode()
                )
                identity = hashlib.sha256(f"{repetition}:{index}".encode()).hexdigest()
                arms = ("plain", "verified") if (index + repetition) % 2 else ("verified", "plain")
                for arm in arms:
                    row = {
                        "id": identity,
                        "scenario": spec[0],
                        "repeat": repetition,
                        "arm": arm,
                        "truth": spec[1],
                        "prediction": None,
                        "error": None,
                        "input_tokens": None,
                        "output_tokens": None,
                        "request_attempted": False,
                    }
                    started = time.monotonic()
                    try:
                        context = (
                            collect_session_evidence(lab.service, signal, lab.principal)
                            if arm == "verified"
                            else None
                        )
                        messages = [
                            {
                                "role": "system",
                                "content": GROUNDED_INSTRUCTIONS
                                + ("\n" + VERIFIED_SESSION_INSTRUCTIONS if context else ""),
                            },
                            *grounded_input(signal.event, context),
                        ]
                        raw = (
                            json.dumps(
                                {"id": identity, "arm": arm, "messages": messages},
                                ensure_ascii=False,
                            )
                            + "\n"
                        ).encode()
                        with (private / "inputs.jsonl").open("ab") as f:
                            f.write(raw)
                        row["input_sha256"] = hashlib.sha256(raw).hexdigest()
                        amount = reservation(messages, INPUT_RATE, OUTPUT_RATE, 2400)
                        if attempts >= 48 or reserved + amount > max_budget:
                            fatal = "budget_or_request_limit"
                            raise ValueError(fatal)
                        reserved += amount
                        attempts += 1
                        row["request_attempted"] = True
                        before = context.for_event(signal.event) if context else None
                        response = await client.responses.parse(
                            model=MODEL,
                            store=False,
                            service_tier="default",
                            reasoning={"effort": "low"},
                            text={"verbosity": "low"},
                            max_output_tokens=2400,
                            input=messages,
                            text_format=grounded_output_type(signal.event, context),
                        )
                        row.update(
                            resolved_model=response.model,
                            input_tokens=response.usage.input_tokens,
                            output_tokens=response.usage.output_tokens,
                        )
                        if response.output_parsed is None:
                            raise ValueError("missing_structured_output")
                        row["raw_assessment"] = response.output_parsed.model_dump(mode="json")
                        a = validate_grounded(response.output_parsed, signal.event, context)
                        if context:
                            after = collect_session_evidence(
                                lab.service, signal, lab.principal
                            ).for_event(signal.event)
                            before.pop("collected_at")
                            after.pop("collected_at")
                            if before != after:
                                raise ValueError("context_changed_during_call")
                        row.update(
                            prediction=prediction(a),
                            assessment=a.model_dump(mode="json"),
                            verification_context=context.for_event(signal.event)
                            if context
                            else None,
                        )
                    except Exception as exc:  # noqa: BLE001 -- no credential-bearing provider text
                        row["error"] = type(exc).__name__
                        if type(exc).__name__ in {
                            "AuthenticationError",
                            "PermissionDeniedError",
                            "RateLimitError",
                            "NotFoundError",
                        }:
                            fatal = type(exc).__name__
                    row["latency_seconds"] = time.monotonic() - started
                    rows.append(row)
                    with (private / "predictions.jsonl").open("ab") as f:
                        f.write((json.dumps(row, ensure_ascii=False) + "\n").encode())
                    print(
                        json.dumps(
                            {"request": attempts, "arm": arm, "status": row["error"] or "ok"}
                        ),
                        flush=True,
                    )
                    if fatal:
                        break
                if fatal:
                    break
            if fatal:
                break
    # Retain the entire predeclared cohort if calls stop before completion.
    seen = {(r["repeat"], r["scenario"], r["arm"]) for r in rows}
    for repeat in range(2):
        for index, spec in enumerate(SCENARIOS):
            for arm in ("plain", "verified"):
                if (repeat, spec[0], arm) not in seen:
                    rows.append(
                        {
                            "id": hashlib.sha256(f"{repeat}:{index}".encode()).hexdigest(),
                            "repeat": repeat,
                            "scenario": spec[0],
                            "arm": arm,
                            "truth": spec[1],
                            "prediction": None,
                            "error": "not_attempted",
                        }
                    )
    by_repeat = {}
    for repeat in range(2):
        parts = {
            arm: [r for r in rows if r["repeat"] == repeat and r["arm"] == arm]
            for arm in ("plain", "verified")
        }
        by_repeat[str(repeat)] = {
            "metrics": {a: metrics(z) for a, z in parts.items()},
            "comparison": compare_rows(parts["plain"], parts["verified"]),
        }
    usage = sum(
        (r.get("input_tokens") or 0) * INPUT_RATE + (r.get("output_tokens") or 0) * OUTPUT_RATE
        for r in rows
    )
    report = {
        "schema": plan["schema"],
        "completed": attempts == 48 and fatal is None,
        "fatal": fatal,
        "attempts": attempts,
        "reserved_upper_usd": reserved,
        "known_usage_estimated_usd": usage,
        "unknown_usage_attempts": sum(
            r.get("request_attempted", False) and r.get("input_tokens") is None for r in rows
        ),
        "unattempted": sum(r.get("error") == "not_attempted" for r in rows),
        "by_repeat": by_repeat,
        "plan_sha256": sha(directory / "plan.json"),
        "independent_evaluation": False,
        "original_historical_metrics_updated": False,
        "external_enterprise_SSO": False,
        "billing_is_provider_invoice_authoritative": True,
    }
    (directory / "report.json").write_bytes((json.dumps(report, indent=2) + "\n").encode())
    print(json.dumps(report), flush=True)
    return report


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--directory", type=Path, required=True)
    p.add_argument("--key-env-file", type=Path)
    p.add_argument("--max-budget", type=float, default=2.5)
    args = p.parse_args()
    try:
        result = asyncio.run(run(args.directory, args.key_env_file, max_budget=args.max_budget))
        if not result["completed"]:
            raise SystemExit(1)
    except Exception as error:  # noqa: BLE001 -- secret-safe CLI
        print(json.dumps({"completed": False, "error_code": type(error).__name__}))
        raise SystemExit(1) from None
