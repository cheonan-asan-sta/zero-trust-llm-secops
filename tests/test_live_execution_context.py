def policy(tmp_path, *, version=1, rules=None):
    from datetime import UTC, datetime
    now = datetime.now(UTC)
    value = ingress.ExecutionPolicy(version=version, issued_at=now,
        expires_at=now+timedelta(hours=1), rules=[] if rules is None else rules)
    path = tmp_path/'policy.json'
    path.write_bytes(canonical(value.model_dump(mode='json')))
    return ingress.PinnedExecutionPolicy(path, hashlib.sha256(path.read_bytes()).hexdigest()), now


@pytest.mark.parametrize('mutation', ['hash', 'expired', 'version', 'link', 'duplicate'])
def test_policy_is_pinned_current_bounded_and_unambiguous(tmp_path, mutation):
    p, now = policy(tmp_path)
    if mutation == 'hash':
        p.path.write_bytes(p.path.read_bytes()+b' ')
    elif mutation == 'expired':
        now += timedelta(hours=1)
    elif mutation == 'version':
        p.minimum_version = 2
    elif mutation == 'link':
        # Portable missing-file equivalent; symlinks are separately denied by code.
        p.path = tmp_path/'absent'
    else:
        rule = ingress.ExecutionRule(tenant_id='t', server_id='s', unit='x.service',
            executable_sha256='a'*64, command_sha256='b'*64, real_uid=0, effective_uid=0)
        p, now = policy(tmp_path, rules=[rule, rule])
    with pytest.raises(ValueError):
        p.current(now)


