def check(context, **updates):
    f, capture, joiner, event, proofs, _ = context
    values = {'capture': capture, 'scope': f.scope, 'joiner': joiner, 'event': event,
                  'proofs': proofs, 'cursor_sha256': capture.records[0].cursor_sha256, 'now': f.now}
    values.update(updates)
    return ingress.collect_pam_context(**values)


def test_exact_signed_pam_runtime_policy_context_adds_only_review_alert(context):
    result = check(context)
    assert result.state == 'adverse' and result.evidence_sha256
    assert result.caller_state == 'unavailable' and result.caller_ref_sha256 is None
    assert not result.organization_identity_verified and not result.automatic_enforcement_allowed
    before = OperationDecision(.1, .1, False, False, 'before')
    after = ingress.refine_pam(before, result)
    assert after.alert and after.review and not after.automatic_enforcement_allowed


